import { test } from 'node:test';
import { fileURLToPath } from 'node:url';
import { verifyStorybookDeclarations } from './ui-storybook-declarations.mjs';

test('Storybook build preserves UI declarations generated by the library build', () => {
  const root = fileURLToPath(new URL('../..', import.meta.url));
  const count = verifyStorybookDeclarations(root);
  console.log(`Verified ${count} UI declarations`);
});
